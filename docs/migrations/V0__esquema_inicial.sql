-- D-P0-3: Esquema inicial SQL para instalaciones limpias sin ddl automático.
-- Precedente de V1__propietario_perfil.sql .. V10__instante_operativo_pago.sql.

CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_usuario_nombre UNIQUE (nombre),
    CONSTRAINT ck_usuario_rol CHECK (rol IN ('PROPIETARIO', 'ASISTENTE'))
);

CREATE TABLE IF NOT EXISTS auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario (id) ON DELETE RESTRICT,
    instante TIMESTAMP WITH TIME ZONE NOT NULL,
    correlacion UUID NOT NULL,
    accion VARCHAR(80) NOT NULL,
    referencia VARCHAR(160) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_auditoria_actor_instante
    ON auditoria (usuario_id, instante);

CREATE TABLE IF NOT EXISTS configuracion (
    clave VARCHAR(80) PRIMARY KEY,
    valor VARCHAR(500) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS propiedad (
    id UUID PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    direccion VARCHAR(300) NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS unidad (
    id UUID PRIMARY KEY,
    propiedad_id UUID NOT NULL REFERENCES propiedad (id) ON DELETE RESTRICT,
    codigo VARCHAR(30) NOT NULL,
    tipo VARCHAR(24) NOT NULL,
    estado VARCHAR(24) NOT NULL,
    canon_referencia NUMERIC(19, 2) NOT NULL,
    moneda VARCHAR(3) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_unidad_propiedad_codigo UNIQUE (propiedad_id, codigo)
);

CREATE TABLE IF NOT EXISTS inquilino (
    id UUID PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL,
    identificacion VARCHAR(40) UNIQUE,
    telefono VARCHAR(30),
    correo VARCHAR(254),
    contacto_emergencia VARCHAR(200),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS contrato (
    id UUID PRIMARY KEY,
    unidad_id UUID NOT NULL REFERENCES unidad (id) ON DELETE RESTRICT,
    inquilino_id UUID NOT NULL REFERENCES inquilino (id) ON DELETE RESTRICT,
    inicio DATE NOT NULL,
    fin DATE NOT NULL,
    canon NUMERIC(19, 2) NOT NULL,
    moneda VARCHAR(3) NOT NULL,
    dia_pago INTEGER NOT NULL,
    deposito_pactado NUMERIC(19, 2) NOT NULL DEFAULT 0,
    estado VARCHAR(24) NOT NULL,
    terminado_el DATE,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS cargo (
    id UUID PRIMARY KEY,
    contrato_id UUID NOT NULL REFERENCES contrato (id) ON DELETE RESTRICT,
    tipo VARCHAR(24) NOT NULL,
    periodo DATE NOT NULL,
    fecha_emision DATE NOT NULL,
    vence_el DATE NOT NULL,
    importe NUMERIC(19, 2) NOT NULL,
    concepto VARCHAR(300) NOT NULL,
    estado VARCHAR(24) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS tipo_cambio (
    id UUID PRIMARY KEY,
    fecha DATE NOT NULL,
    nio_por_usd NUMERIC(19, 8) NOT NULL,
    fuente VARCHAR(500) NOT NULL,
    registrado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    autorizado_por BIGINT REFERENCES usuario (id) ON DELETE RESTRICT,
    motivo VARCHAR(500)
);

CREATE INDEX IF NOT EXISTS ix_tipo_cambio_fecha_registrado_en
    ON tipo_cambio (fecha, registrado_en);

CREATE TABLE IF NOT EXISTS pago (
    id UUID PRIMARY KEY,
    contrato_id UUID NOT NULL REFERENCES contrato (id) ON DELETE RESTRICT,
    fecha_pago DATE NOT NULL,
    moneda_original VARCHAR(3) NOT NULL,
    monto_original NUMERIC(19, 2) NOT NULL,
    monto_contrato NUMERIC(19, 2) NOT NULL,
    moneda_contrato VARCHAR(3) NOT NULL,
    metodo VARCHAR(24) NOT NULL,
    referencia VARCHAR(100),
    notas VARCHAR(255),
    estado VARCHAR(24) NOT NULL,
    tipo_cambio_id UUID REFERENCES tipo_cambio (id) ON DELETE RESTRICT,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS recibo (
    numero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id UUID NOT NULL UNIQUE REFERENCES pago (id) ON DELETE RESTRICT,
    contrato_info TEXT NOT NULL
);
